# frozen_string_literal: true

module Shaka
  class Seam
    class UpgradePlan
      # Files inside the old directory can name moved files relative to themselves.
      module RelativeReferences
        private

        def rewrite_relative_references(path, text, executable)
          mapping = relative_mapping(path)
          return text if mapping.empty?

          strict = executable ? :all : (:root_like unless generated_pointer?(path, text))
          text.lines.map { |line| rewrite_relative_line(path, line, mapping, strict) }.join
        end

        def rewrite_relative_line(path, line, mapping, strict)
          found = mapping.keys.select { |old| line.match?(relative_pattern(old)) }
          return line if found.empty?

          @references << { 'path' => path, 'kind' => 'relative old-layout reference',
                           'paths' => found.map { |old| mapping.fetch(old).last } }
          return historical_reference(path, line) if historical_line?(path, line)
          return block_relative_reference(path, found, line) if blocked_relative?(line, found, strict)

          replace_relative(line, found, mapping)
        end

        def replace_relative(line, found, mapping)
          found.reduce(line) do |result, old|
            result.gsub(relative_pattern(old)) { "#{::Regexp.last_match[:lead]}#{mapping.fetch(old).first}" }
          end
        end

        def blocked_relative?(line, found, strict)
          strict == :all || split_directory?(line, found) || (strict == :root_like && root_like?(line, found))
        end

        # A hand-written note in the old directory may mean the repository's own bin/; only Shaka's generated
        # pointer is known to mean the old command directory.
        def root_like?(line, found)
          prefix = "#{File.basename(PATHS::COMMAND_DIRECTORY)}/"
          found.any? { |spelling| spelling.start_with?(prefix) && line.match?(relative_pattern(spelling, lead: false)) }
        end

        def generated_pointer?(path, text)
          [PATHS::POINTER, PATHS::LEGACY_README].include?(path) && text.start_with?('<!-- Generated by ')
        end

        def block_relative_reference(path, found, line)
          @blockers << "#{path}: relative old-layout reference #{found.join(', ')} needs explicit repair"
          line
        end

        # Helper tools stay in the old command directory, so a pattern over it, or any mention of it
        # while a tracked tool stays there, has no single new home. A Markdown note is not a tool.
        def split_directory?(line, found)
          found.any? do |spelling|
            line.match?(relative_pattern(spelling, '[*?\\[]')) || (spelling.end_with?('/') && retained_command_file?)
          end
        end

        def retained_command_file?
          moved = @moves.map { |move| move.fetch('from') }
          @tracked_reference_paths.keys.any? do |path|
            path.start_with?("#{PATHS::COMMAND_DIRECTORY}/") && !moved.include?(path) && !markdown_path?(path)
          end
        end

        def relative_reference_file?(path) = !relative_mapping(path).empty?

        def relative_reference?(path, text)
          relative_mapping(path).keys.any? { |spelling| text.match?(relative_pattern(spelling)) }
        end

        # Maps each spelling to [new spelling, old path]. A bare command name is prose, so only
        # spellings with a slash and the two YAML names beside their old files count.
        def relative_mapping(path)
          directory = File.dirname(path)
          return {} unless inside_old_directory?(directory)

          relative_targets.each_with_object({}) do |(old, new), mapping|
            spelling = relative_to(old, directory)
            next if spelling == './'

            mapping[spelling] = [relative_to(new, directory), old] if spelling.include?('/') || yaml_file?(old)
          end
        end

        def yaml_file?(path) = [PATHS::CONTRACT, PATHS::REPOSITORY_ALLOWLIST].include?(path)

        def inside_old_directory?(directory)
          new_directory = File.dirname(PATHS::NEW_CONTRACT)
          (directory == PATHS::DIRECTORY || directory.start_with?("#{PATHS::DIRECTORY}/")) &&
            directory != new_directory && !directory.start_with?("#{new_directory}/")
        end

        def relative_targets
          reference_mapping.merge("#{PATHS::COMMAND_DIRECTORY}/" => "#{PATHS::NEW_COMMAND_DIRECTORY}/")
        end

        def relative_to(target, directory)
          relative = Pathname(target).relative_path_from(Pathname(directory)).to_s
          target.end_with?('/') ? "#{relative}/" : relative
        end

        def relative_pattern(spelling, ending = nil, lead: true)
          ending ||= spelling.end_with?('/') ? '(?![[:alnum:]_.-])' : path_end
          Regexp.new("(?<![[:alnum:]_./-])#{'(?<lead>\\./)?' if lead}#{Regexp.escape(spelling)}#{ending}")
        end
      end
    end
  end
end
