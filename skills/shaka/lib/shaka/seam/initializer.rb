# frozen_string_literal: true

require 'yaml'
require_relative '../repository_config'
require_relative 'initializer_destination'
require_relative 'initializer_input'

module Shaka
  class Seam
    # Creates the smallest complete repository seam without replacing repo-owned files.
    class Initializer
      MARKER = 'Generated by shaka seam init.'
      COMMAND_NAMES = %w[setup validate test].freeze

      include InitializerInput
      include InitializerDestination

      def initialize(root:, options:)
        @root = root
        @options = options
      end

      def call
        files = generated_files
        preflight_directories
        preflight_files(files)
        write_files(files)
        RepositoryConfig.load(root: @root)
      end

      private

      def generated_files
        wrappers = COMMAND_NAMES.to_h do |name|
          command = required("#{name}_command").then { |value| command_arguments(value, name) }
          [File.join(@root, '.agents/bin', name), wrapper(command)]
        end
        wrappers.merge(File.join(@root, RepositoryConfig::PATH) => config_source)
      end

      def config_source
        config = config_hash
        if @options[:plan]
          repository_file(@options[:plan], 'plan')
          config['plan'] = @options[:plan]
        end
        actions = string_list(:trusted_actions, 'trusted_action')
        config['trusted_actions'] = actions unless actions.empty?
        "# #{MARKER}\n#{YAML.dump(config)}"
      end

      def config_hash
        {
          'version' => 1,
          'base_branch' => base_branch,
          'commands' => COMMAND_NAMES.to_h { |name| [name, ".agents/bin/#{name}"] },
          'review' => review_policy,
          'merge' => merge_policy,
          'protection' => protection_policy,
          'branches' => { 'name' => '{login}-{host}/{issue}-{description}' }
        }
      end

      def review_policy
        required_policy = required('review_policy')
        if required_policy == 'none'
          raise Error, '--review-check must be omitted when review policy is none' if @options.key?(:review_check)

          return { 'required' => required_policy }
        end

        { 'required' => required_policy, 'check' => required('review_check') }
      end

      def merge_policy
        { 'preference' => @options.fetch(:merge_preference, 'ask'),
          'method' => 'squash', 'release' => 'explicit_approval' }
      end

      def protection_policy
        { 'required_checks' => required_list(:required_checks, 'required_check'),
          'direct_push' => false, 'force_push' => false, 'branch_deletion' => false }
      end

      def wrapper(arguments)
        <<~SHELL
          #!/bin/sh
          # #{MARKER}
          set -eu
          root=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
          cd "$root"
          exec #{arguments.shelljoin} "$@"
        SHELL
      end
    end
  end
end
