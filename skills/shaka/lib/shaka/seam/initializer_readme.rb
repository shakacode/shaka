# frozen_string_literal: true

require_relative '../version'
require_relative '../configuration/paths'
require_relative '../defaults'

module Shaka
  class Seam
    # Explains the generated seam directory by pointing at the reference, not restating it.
    module InitializerReadme
      HOME = 'https://github.com/shakacode/shaka'
      DOCS = "#{HOME}/blob/main/docs".freeze
      # Shows the default a maintainer most often changes, so config.yml names the file Shaka reads.
      CONFIG_TRAILER = ['', 'Defaults you can change (https://shaka.shakacode.com/docs/settings#checkpoint):',
                        'checkpoint:',
                        '  # Your instructions, added after the checkpoint prompt. Commented out, the file is',
                        '  # optional; uncommented, a missing file fails settings validation.',
                        "  custom_instructions_file: #{Defaults.fetch('checkpoint', 'custom_instructions_file')}",
                        "  # Or replace Shaka's whole checkpoint prompt with your own file:",
                        '  # replacement_prompt_file: .agents/shaka/checkpoint-prompt.md'].freeze

      private

      def config_trailer = CONFIG_TRAILER

      def readme_source
        <<~MARKDOWN
          #{readme_marker}
          # Shaka configuration

          This repository uses Shaka #{Shaka::VERSION} (pilot stage #{Shaka::PRODUCT_STAGE})
          with contract `version: 1`. The files below hold its configuration.

          | Path | Purpose |
          | --- | --- |
          | `#{pointer_relative(Configuration::Paths::CONTRACT)}` | Review, merge, and branch policy, read from the trusted default branch. Live GitHub settings still govern checks and approvals. |
          | `#{pointer_relative(Configuration::Paths::COMMAND_DIRECTORY)}/` | Executable setup, test, and validation wrappers. Shaka runs the candidate checkout's copies; inspect changes before execution. |

          ## Check configuration edits

          `shaka seam check --root . --local`

          Validates the current checkout's YAML and scripts. Without `--ref`, it
          grants no trusted policy authority.

          ## Load trusted policy

          Resolve this repository's default branch to an immutable commit SHA, then:

          `shaka seam check --root . --ref SHA`

          A candidate PR cannot grant itself authority by changing its own policy.
          Copy-ready `AGENTS.md` guidance: `shaka seam pointer`.

          - [Configuration reference](#{DOCS}/settings.md) — every key, its type, and what it controls.
          - [Repository setup](#{DOCS}/configure-repository.md) — how this directory was created.

          Generated by `#{generated_by}` from Shaka #{Shaka::VERSION}. Repeating that command
          leaves this file alone; it never overwrites one you have edited.
        MARKDOWN
      end

      def pointer_relative(path) = path.delete_prefix("#{Configuration::Paths::DIRECTORY}/")

      def readme_marker = "<!-- Generated by #{generated_by}. -->"

      def generated_by = 'shaka seam init'
    end
  end
end
